// Кто участвует в гонке доказательств выхода (см. :core EgressRace).
//
// ⏱️ Зачем гонка вообще — в шапке EgressRace.kt (замер 20-08: из шести секунд до «Защищено» больше
// половины уходило на ОДНУ пробу через api.ipify.org, а не на туннель). Здесь — состав участников и
// почему их ровно двое.
//
// 1️⃣ НАШЕ ЯДРО ПО СЫРОМУ IP — `https://<ip>:8443/v1/egress-check`.
//    Ручка на ядре уже есть и заведена ровно под этот вопрос: она отвечает `{"ip":…,"country":…}`,
//    где ip — адрес, КАКИМ ЕГО ВИДИТ ЯДРО (internal/clientapi/egresscheck.go). Через поднятый туннель
//    это адрес выходной ноды — то самое доказательство и то самое число, которое мы показываем.
//    Авторизация не нужна (ручка публичная — её же бьют сами ноды в health-петле).
//    Главное преимущество — БЕЗ РЕЗОЛВА ИМЕНИ. Резолв через только что поднятый туннель и есть самая
//    дорогая и самая ненадёжная часть пробы: в замере 20-08 первая проба провалилась именно на нём
//    («UnknownHostException: Unable to resolve host "api.ipify.org"»), а в разборе 27-07 системный
//    резолвер через мёртвый туннель занимал ~28 с в одиночку. Сырому IP доверяем по ВШИТОМУ CA
//    (`ui/src/prodRelease/res/xml/network_security_config.xml`, `Mayak Prod CA E1`), то есть путь ещё
//    и не зависит от публичных корней.
//    ⚠️ Лимит на ядре — 120 запросов/мин на IP, а через туннель ВСЕ люди одной ноды приходят под
//    одним адресом (адресом выхода). Сегодня людей единицы и лимит недостижим; когда их станут сотни,
//    лимит `egressLimit` в ядре придётся поднять. Пока этого не сделано, 429 не ломает подключение —
//    он просто означает «этот участник не ответил», и выигрывает второй.
//
// 2️⃣ НЕЗАВИСИМЫЙ ТРЕТИЙ — `api.ipify.org`. Оставлен НАМЕРЕННО, а не «на всякий случай»: он проверяет
//    выход в ЧУЖУЮ сеть, а не только до нашего же ядра. Если однажды у ноды отвалится связность со
//    всем интернетом, кроме Амстердама, первый участник этого не увидит, а этот — увидит.
//
// 🔴 Почему НЕ третьим участником домен `api.mayaknetworks.com`. Он ничего не добавляет: то же ядро,
// тот же ответ, но через резолв — то есть ровно через ту часть, от которой мы уходим. А каждое лишнее
// соединение в момент подъёма туннеля не бесплатно (урок 20-08 про восемь рукопожатий на старте:
// параллельные TLS на узком канале мешают друг другу). Двух участников достаточно, чтобы закрыть обе
// причины отказа — «не резолвится» и «наш сервис недоступен».
package org.amnezia.awg.mayak

import android.content.Context
import org.amnezia.awg.mayak.core.EgressProbe

object MayakEgressProbes {

    /** Независимый внешний сервис. v4-only host: `api6.` — отдельный, он живёт в IPv6-пробе. */
    private const val IPIFY_V4 = "https://api.ipify.org?format=json"

    /**
     * Участники гонки для ПРОВЕРКИ ВЫХОДА ПО IPv4 — в том порядке, в каком их запускать
     * (порядок роли не играет: они стартуют одновременно, но читать список приятнее сверху вниз).
     *
     * @param savedServer сервер, заданный руками в настройках (может быть null) — он же первым идёт
     *        в списке адресов ядра, и если человек прописал свой, проба обязана идти туда же.
     */
    fun v4(context: Context, savedServer: String?): List<EgressProbe> {
        val out = ArrayList<EgressProbe>(2)
        coreEgressCheckUrl(context, savedServer)?.let {
            out.add(HttpEgressProbe(url = it, label = "ядро"))
        }
        out.add(HttpEgressProbe(url = IPIFY_V4, label = "ipify"))
        return out
    }

    /**
     * Адрес нашего `/v1/egress-check`, ПРЕДПОЧТИТЕЛЬНО по сырому IP (без резолва).
     *
     * Список адресов ядра берём живой (`MayakHostList.effective`) — вшитый IP протухнет при переезде
     * ядра, а реестр доменов и подписанный delivery-документ приносят актуальный. Домена не нашлось
     * вовсе — вернём null и обойдёмся одним внешним участником: гонка из одного всё равно работает.
     */
    private fun coreEgressCheckUrl(context: Context, savedServer: String?): String? {
        val hosts = MayakHostList.effective(context, savedServer)
        val byIp = hosts.firstOrNull { base -> MayakHostList.hostOf(base)?.let(::isAddress) == true }
        // Домен берём ТОЛЬКО если адреса-IP в списке нет вовсе. Смысл участника — обойти резолв;
        // домен здесь — не «лучше, чем ничего», а «ровно то же, что и ipify, но у нас».
        val base = byIp ?: hosts.firstOrNull() ?: return null
        return base.trimEnd('/') + "/v1/egress-check"
    }

    /**
     * Хост — это адрес (IPv4/IPv6), а не имя?
     *
     * Признак простой и достаточный: в адресе НЕТ БУКВ (v4: `2.26.77.243`) либо он записан в скобках
     * (v6: `[2a12:bec4::2]`, буквы там шестнадцатеричные). Полноценный разбор адреса тут не нужен:
     * цена ошибки — участник пойдёт через резолв, как раньше, а не сломается.
     */
    private fun isAddress(host: String): Boolean =
        host.none { it.isLetter() } || host.contains(':')
}
