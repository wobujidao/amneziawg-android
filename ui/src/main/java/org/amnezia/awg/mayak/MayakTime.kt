// Относительное время («5 минут назад») — ОДНО на всё приложение.
//
// Было четыре одинаковых копии `ago()` (обращения, нитка обращения, ящик сообщений, устройства), и во
// всех четырёх один и тот же изъян: время приходит С СЕРВЕРА, а сравнивается с часами ТЕЛЕФОНА. Часы
// расходятся всегда — на секунды у обычного человека, на минуты у того, у кого сбито время, — и
// свежая запись легко оказывается «в будущем». Android в этом случае честно пишет «через 0 минут»
// («In 0 minutes»), что человек читает как ошибку приложения. Снято на эмуляторе 16-08 сразу после
// отправки обращения.
//
// Лечение: будущее подтягиваем к «сейчас». Мы показываем ДАВНОСТЬ события, которое уже случилось, —
// отрицательной она не бывает по смыслу, и «только что» тут единственный честный ответ.
package org.amnezia.awg.mayak

import android.text.format.DateUtils

object MayakTime {

    /**
     * Момент [ms] в прошлом относительно [now]: будущее подтягивается к «сейчас».
     *
     * Чистая функция, чтобы правило проверялось тестом, а не глазами: для [ago] нужен Android.
     */
    fun clampToPast(ms: Long, now: Long): Long = if (ms > now) now else ms

    /** «5 минут назад» на языке приложения. Событие в будущем показывается как «только что». */
    fun ago(ms: Long): CharSequence {
        val now = System.currentTimeMillis()
        return DateUtils.getRelativeTimeSpanString(clampToPast(ms, now), now, DateUtils.MINUTE_IN_MILLIS)
    }
}
