// Жёсткий срок ожидания — работает даже поверх БЛОКИРУЮЩЕГО вызова.
package org.amnezia.awg.mayak.core

import kotlinx.coroutines.CoroutineScope
import kotlinx.coroutines.async
import kotlinx.coroutines.withTimeoutOrNull

/**
 * Ждать результат [block] не дольше [ms]; не дождались — `null`.
 *
 * Зачем отдельная функция, если есть `withTimeoutOrNull`. Отмена корутин КООПЕРАТИВНАЯ: если внутри
 * блокирующий вызов (сокет, системный резолвер), `withContext(Dispatchers.IO) { … }` не вернётся,
 * пока этот вызов не отработает сам. `withTimeoutOrNull` обязан дождаться своих детей — и молча
 * ждёт вместе с ними. Срок соблюдается на бумаге и не соблюдается в жизни.
 *
 * Чем это кончилось у людей (диаг-лог владельца #71, Мегафон, 0.3.78): на проверку выхода отводилось
 * 5 с, а решение уйти на следующую ступень лестницы приняли через 29 034 мс — внутри пробы системный
 * резолвер ~28 с перебирал DNS-серверы ЧЕРЕЗ мёртвый туннель. Человек полминуты смотрел на
 * «Подключаюсь…», хотя запасной путь рядом поднимался за секунду.
 *
 * Приём: тело запускаем ОТДЕЛЬНОЙ задачей в переданной области [scope] (не дочерней текущей
 * корутине), а ждём `await()` — настоящую точку приостановки, которую таймаут прерывает мгновенно.
 * Осиротевшая задача досидит своё и умрёт сама; её результат нам уже не нужен.
 *
 * [scope] должен переживать вызов (например, поле объекта) — область самого вызывающего не подойдёт,
 * иначе задача снова станет дочерней и мы вернёмся к исходной ловушке.
 */
suspend fun <T> awaitAtMost(scope: CoroutineScope, ms: Long, block: suspend () -> T): T? {
    val running = scope.async { block() }
    val value = withTimeoutOrNull(ms) { running.await() }
    // best-effort: блокирующее тело так не прервать, но поток освободится сразу, как только оно
    // дойдёт до ближайшей точки отмены.
    if (value == null) running.cancel()
    return value
}
