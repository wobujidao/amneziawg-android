// Решение «показывать ли знакомство» — чистое правило, отдельно от Android, чтобы проверялось
// юнит-тестом на обычном JVM. Зеркалит устройство AlwaysOnNudge: там разговор ПОСЛЕ первого
// подключения, здесь — ДО него.
//
// Зачем знакомство: человек, впервые открывший приложение, видит круглую кнопку и список стран, и
// ничего не объясняет ему, что тапнуть кнопку достаточно, а страну можно менять на живом туннеле.
// Пустое состояние и ошибка загрузки списка разведены давно (0.4.1), а вот «что это и как этим
// пользоваться» не говорил никто.
package org.amnezia.awg.mayak.core

object Onboarding {

    /**
     * Показывать ли лист знакомства.
     *
     * @param alreadyShown уже показывали (ответ запоминается навсегда — второй раз это раздражение,
     *   а не помощь).
     * @param signedIn человек вошёл в аккаунт. До входа знакомить не с чем: экран входа сам себя
     *   объясняет, а лист поверх него — лишняя дверь перед дверью.
     * @param connectCount сколько раз уже подключался. Больше нуля — знакомство опоздало: человек
     *   разобрался сам, и рассказывать ему «нажмите кнопку» поздно и обидно. Так бывает у тех, кто
     *   обновился со старой сборки, где листа не было.
     */
    fun shouldShow(alreadyShown: Boolean, signedIn: Boolean, connectCount: Int): Boolean =
        !alreadyShown && signedIn && connectCount == 0
}
