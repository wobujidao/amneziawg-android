// Почему ядро отказало в доступе — разбор машинного признака 402.
//
// Зачем отдельный файл, а не `when` внутри экрана. Ядро с 2026-08-08 различает две причины, которые
// приходят под ОДНИМ HTTP-кодом 402 (internal/clientapi/server.go: RegisterDevice и /connect):
//   • `no_plan`         — тарифа аккаунту не выдавали ВОВСЕ; лечится ВЫБОРОМ тарифа;
//   • `no_subscription` — тариф был, срок прошёл; лечится ПРОДЛЕНИЕМ.
// Приложение ветвилось только по статусу и обоим показывало «Доступ закончился — продлите», то есть
// человеку, который ни разу не платил, советовало продлить то, чего у него не было. Кабинет эти два
// случая уже развёл словами («доступ ещё не открыт» / «срок доступа закончился»), приложение — нет.
//
// Решение вынесено в :core чистой функцией, чтобы его можно было проверить юнит-тестом на JVM:
// внутри Activity оно проверяемо только эмулятором, а именно оно и было неверным.
package org.amnezia.awg.mayak.core

/** Причина отказа в доступе (402). */
enum class AccessDenial {
    /** Тарифа у аккаунта нет — продлевать нечего, надо ВЫБРАТЬ тариф. */
    NO_PLAN,

    /** Доступ был и закончился — надо ПРОДЛИТЬ. */
    EXPIRED,

    /** Отказ не про доступ (другой статус) — пусть разбирается общая ветка. */
    NONE,
}

/**
 * Разбор отказа: HTTP-код + машинный признак `code` из тела → причина.
 *
 * Fail-safe: 402 без признака или с НЕЗНАКОМЫМ признаком читаем как [AccessDenial.EXPIRED] — это
 * поведение, которое было до правки. Старое ядро (или ядро, где завели третью причину) не должно
 * ронять клиента в общую «ошибку ядра»: человек увидит текст чуть менее точный, но осмысленный, и
 * попадёт в кабинет, где написана правда.
 */
fun accessDenial(status: Int, code: String): AccessDenial {
    if (status != 402) return AccessDenial.NONE
    return if (code == "no_plan") AccessDenial.NO_PLAN else AccessDenial.EXPIRED
}
