// EgressRace — «Защищено» по ПЕРВОМУ доказательству выхода, а не по единственному.
//
// ⏱️ ОТКУДА ЭТО ВЗЯЛОСЬ (замер 2026-08-20, Android 9, боевая сборка, живой прод).
// Разложение подключения по логам: тап → регистрация устройства и /connect ≈ 2,5 с → туннель поднят,
// рукопожатие ПРОШЛО за 190 мс → и дальше человек ещё **~3,3 секунды** смотрит на «Проверяем, что
// интернет пошёл…». Итого «Защищено» примерно через 6 секунд, из которых сам туннель — меньше трёх.
// Половина времени подключения уходила не на туннель, а на ОДНУ пробу выхода, которая делает всё
// подряд и по очереди: резолв имени через свежий туннель → TCP → TLS → GET → разбор JSON.
//
// 🔴 Чего здесь СОЗНАТЕЛЬНО не сделано: «показать Защищено раньше». Честность статуса в этом проекте
// выстрадана (0.3.x: приложение говорило «Защищено» при мёртвом выходе). Статус обязан означать
// ДОКАЗАННЫЙ выход, поэтому ускоряется сама проба, а не критерий.
//
// Приём — гонка: несколько независимых доказательств выхода стартуют ОДНОВРЕМЕННО, побеждает первое
// ответившее, остальные бросаются. Это даёт три вещи сразу:
//   1) время = время САМОГО БЫСТРОГО участника, а не единственного (медленный резолв одного больше
//      никого не задерживает);
//   2) одна точка отказа превращается в несколько: внешний сервис нас рейт-лимитит или лежит —
//      подключение больше не встаёт (ровно на этом обожглись на ipinfo.io 2026-07-11, когда 429 в
//      ответ ноде давал ложное «выход не работает»);
//   3) участником может быть НАШ /v1/egress-check по сырому IP — то есть путь совсем БЕЗ резолва
//      имени, а резолв через только что поднятый туннель и есть самая дорогая часть (см. Deadline.kt:
//      при мёртвом туннеле он один занимал ~28 с).
//
// ⚠️ ПОЧЕМУ НЕЛЬЗЯ coroutineScope { async … }. Пробы блокирующие (HttpURLConnection + системный
// резолвер), отмена корутин кооперативная: структурная конкурентность ОБЯЗАНА дождаться своих детей,
// то есть «гонка» ждала бы самого медленного участника — ровно то, от чего мы уходим. Поэтому
// участники запускаются в ЧУЖОЙ, переживающей вызов области [scope] (то же решение, что в
// `awaitAtMost`), а результаты собираются через канал: проигравших мы просто бросаем, они досидят
// свой сокет сами и умрут.
package org.amnezia.awg.mayak.core

import kotlinx.coroutines.CoroutineScope
import kotlinx.coroutines.channels.Channel
import kotlinx.coroutines.launch

object EgressRace {

    /**
     * Гонка проб: первый непустой адрес выигрывает, проигравшие бросаются.
     *
     * @param scope область, ПЕРЕЖИВАЮЩАЯ вызов (поле объекта, не текущая корутина) — см. заметку выше.
     * @param probes участники. Пустой список → null (тогда звать было нечего).
     * @return внешний IP от первого ответившего участника либо null, если выход не подтвердил НИКТО.
     */
    suspend fun first(scope: CoroutineScope, probes: List<EgressProbe>): String? {
        if (probes.isEmpty()) return null
        // UNLIMITED — чтобы `send` НИКОГДА не подвешивал участника: отставший должен уметь досказать
        // свой результат в пустоту и завершиться, а не висеть на канале, который уже никто не читает.
        val inbox = Channel<String?>(Channel.UNLIMITED)
        val running = probes.map { p ->
            scope.launch { inbox.send(runCatching { p.externalIp() }.getOrNull()) }
        }
        try {
            repeat(probes.size) {
                val ip = inbox.receive()
                if (!ip.isNullOrBlank()) return ip
            }
            return null
        } finally {
            // best-effort: блокирующий сокет так не прервать, но поток освободится на ближайшей
            // точке отмены, и второй попытки этот участник уже не займёт.
            running.forEach { it.cancel() }
        }
    }

    /**
     * Паузы между ПОПЫТКАМИ гонки (мс), по порядку.
     *
     * Раньше пауза была одна на всех — 2 с, и она стоила человеку ровно 2 секунды в самом частом
     * случае. Замер 20-08 (лог `before1`): первая проба ушла в момент, когда туннель ещё перестраивался,
     * честно провалилась за 250 мс («UnknownHostException: Unable to resolve host») — и дальше две
     * секунды не делалось НИЧЕГО, хотя повторять можно было сразу. Провал сразу после подъёма туннеля
     * — норма, а не признак мёртвого пути: система только что сменила интерфейс и DNS.
     *
     * Поэтому паузы теперь РАСТУТ: первая короткая (дешёвый повтор по горячим следам), дальние —
     * длинные (там уже ждём, пока сервер заведёт пира: он появляется на выходной ноде следующим
     * поллингом агента, до 15 с — см. FallbackDecision.PEER_SYNC_MS).
     *
     * Сумма НАРОЧНО оставлена прежней — 10 000 мс на пять пауз (было 5 × 2 000). Общее окно ожидания
     * не сократилось: сокращать его значило бы бросать путь раньше, чем на нём появится пир, а это
     * уже другой дефект («с первого раза не подключается, со второго — да»).
     */
    val RETRY_GAPS_MS: List<Long> = listOf(400L, 900L, 1_800L, 3_000L, 3_900L)

    /** Пауза перед попыткой номер [attemptIndex] (нумерация с 0 = пауза ПОСЛЕ первой попытки). */
    fun retryGapMs(attemptIndex: Int): Long =
        RETRY_GAPS_MS[attemptIndex.coerceIn(0, RETRY_GAPS_MS.size - 1)]
}
