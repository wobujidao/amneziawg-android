package org.amnezia.awg.mayak.core

/**
 * Куда :core пишет диагностические строки.
 *
 * Зачем понадобилось. Модуль :core — чистый Kotlin/JVM и НЕ ЗНАЕТ про Android: `android.util.Log`
 * ему недоступен по построению (и это правильно — он собирается и тестируется на обычном JVM).
 * Но именно здесь живёт клиент к API ядра, и именно здесь известен НОМЕР ЗАПРОСА, по которому
 * жалоба человека сшивается с журналом ядра. Без выхода наружу номер оставался бы внутри и никому
 * не помогал.
 *
 * Поэтому один тонкий стык: :ui при старте подставляет сюда свою запись в logcat (её потом
 * подбирает диаг-лог), а тесты на JVM оставляют пустым — и тогда это просто no-op.
 *
 * Намеренно НЕ интерфейс и НЕ инъекция через конструктор: точка одна, вызовов мало, а тянуть
 * логгер через все конструкторы :core ради двух строк — цена больше пользы.
 */
object MayakDiagSink {
    /** Куда писать. null — никуда (тесты, чистый JVM). */
    @Volatile
    var write: ((String) -> Unit)? = null

    fun log(line: String) {
        write?.invoke(line)
    }
}
