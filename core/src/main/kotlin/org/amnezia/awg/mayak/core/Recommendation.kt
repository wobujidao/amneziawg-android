// Плитка «⚡ Рекомендуем» — выбор направления для неё (SPEC-0031 T3, хвост F-T5).
//
// Рекомендацию считает СЕРВЕР (internal/clientapi/recommend.go): среди живых (health=ok) направление
// с наименьшей эффективной загрузкой, ровно одно, признак `recommended:true` в /v1/client/directions.
// Клиент рекомендацию НЕ выдумывает: нет пометки от ядра — нет плитки. Своя эвристика здесь дала бы
// два расходящихся мнения об одном «рекомендуем» (в кабинете/на сервере одно, в приложении другое).
//
// Логика вынесена в :core чистой функцией по приёму соседних фич (AccessDenial, MinVersionGate):
// внутри Activity её проверял бы только эмулятор, а тут — юнит-тест на JVM (RecommendationTest).
package org.amnezia.awg.mayak.core

/**
 * Направление для плитки «⚡ Рекомендуем» или null («плитку не показываем»).
 *
 * Доверяем серверной пометке, но с двумя предохранителями против кривого/старого ядра:
 *  • помечено мёртвое (`health=down`) — не рекомендуем: сервер обещает помечать только живые,
 *    и совет «подключайся сюда» на мёртвом направлении хуже отсутствия совета;
 *  • помечено несколько (нарушение контракта «ровно одно») — берём первое по порядку сервера,
 *    а не прячем плитку: каждое из них сервер считал живым, показать одно — честно.
 */
fun recommendedDirection(dirs: List<Direction>): Direction? =
    dirs.firstOrNull { it.recommended && it.health != "down" }

/**
 * Итог разбора направлений между плиткой «⚡ Рекомендуем» и списком под ней.
 *
 * @property tile направление для плитки, или null — плитки нет вовсе.
 * @property list направления для списка ПОД плиткой — БЕЗ [tile], если он есть: одно и то же
 *  направление показывается ровно один раз на экране, а не плиткой И строкой сразу.
 */
data class RecommendationSplit(val tile: Direction?, val list: List<Direction>)

/**
 * Разбить направления между плиткой и списком (баг 09-08: «Почему тут 2 Нидерланды?» — плитку
 * рисовали НАД списком, а из списка рекомендованное направление не убирали, и один и тот же
 * сервер оказывался на экране дважды).
 *
 * Особый случай — направление ровно одно, и оно же рекомендованное: плитки НЕ показываем, отдаём
 * направление обычной строкой списка (как было до плитки). Решение осознанное, а не техническое
 * ограничение: «рекомендуем» подразумевает выбор среди альтернатив, а альтернатив нет — сравнивать
 * не с чем, и плитка-ярлык на пустом месте только повторяла бы единственную строку под собой без
 * какой-либо новой информации. Второй вариант (показать плитку и подписью объяснить, что других
 * направлений нет) обсуждался и отклонён: он тянет за собой новую локализованную строку в семи
 * языках ради состояния, которое ничем не богаче обычной строки списка.
 */
fun splitRecommended(dirs: List<Direction>): RecommendationSplit {
    val rec = recommendedDirection(dirs) ?: return RecommendationSplit(tile = null, list = dirs)
    if (dirs.size <= 1) return RecommendationSplit(tile = null, list = dirs)
    return RecommendationSplit(tile = rec, list = dirs.filterNot { it.id == rec.id })
}
