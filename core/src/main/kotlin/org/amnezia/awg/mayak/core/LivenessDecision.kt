// LivenessDecision — сколько ещё ждать, прежде чем чинить туннель, у которого не идёт трафик.
//
// Решение вынесено в :core по той же причине, что и FallbackDecision: порог должен быть в ОДНОМ
// месте и проверяться тестом на JVM, а не «на телефоне владельца».
//
// ⚠️ ОТКУДА ВЗЯЛОСЬ ЧИСЛО — из живого лога платящего человека (диаг #28, 15-08, учётка 055-319-424,
// тариф Макс). Там видно ровно две отметки:
//
//   07:50:22  Mayak/Liveness: живость: 1 → 2 (rx вырос=false)   ← фоновый сторож УЖЕ ЗНАЕТ
//   07:50:58  mayak-probe: трафика нет — переподключаюсь сам     ← и только теперь начинаем чинить
//
// Тридцать шесть секунд между «знаем» и «делаем». Их съедал пинг-цикл главного экрана: он считает
// СВОИ промахи с нуля (4 промаха × 5 с) и про вердикт фонового сторожа ничего не знал. А человек в
// это время смотрит на «Защищено» и на страницу, которая не грузится.
//
// Почему просто «чинить сразу» — нельзя. Пинг может не дойти и на живом туннеле (обычное дело на
// соте), а лечение — это опустить и заново поднять туннель, то есть заведомый обрыв. Поэтому нужен
// хотя бы ОДИН свой промах: сторож судит по росту rx и возрасту рукопожатия, пинг — по ответу
// сервера, и совпадение двух независимых признаков и есть подтверждение.
package org.amnezia.awg.mayak.core

object LivenessDecision {

    /** Обычный порог: 4 промаха по 5 с ≈ 20 с. Меньше — ловили бы обычные провалы соты. */
    const val MISSES_NORMAL = 4

    /** Порог, когда фоновый сторож НЕЗАВИСИМО видит, что трафика нет: хватает одного промаха. */
    const val MISSES_WHEN_WATCHDOG_SURE = 1

    /**
     * Сколько промахов пинга подряд нужно, чтобы объявить «трафика нет» и начать лечение.
     *
     * @param watchdogSaysNoTraffic фоновый сторож ([MayakLiveness]) сам, по росту rx и возрасту
     *        рукопожатия, уже пришёл к выводу, что трафика нет.
     */
    fun missesBeforeSelfHeal(watchdogSaysNoTraffic: Boolean): Int =
        if (watchdogSaysNoTraffic) MISSES_WHEN_WATCHDOG_SURE else MISSES_NORMAL
}
