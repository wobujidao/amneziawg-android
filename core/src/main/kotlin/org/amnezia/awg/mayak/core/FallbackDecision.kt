// FallbackDecision — когда пора уходить с UDP на запасной канал (SPEC-0039 T5).
//
// Решение вынесено сюда, в :core, по двум причинам: пороги должны быть В ОДНОМ месте (а не размазаны
// по Activity), и их надо проверять тестом на JVM, а не «на телефоне владельца».
//
// Почему два разных порога, а не один:
//  - хендшейка НЕТ вовсе → наши UDP-пакеты не доходят до сервера в принципе (оператор душит весь UDP —
//    ровно случай, ради которого сделан SPEC-0039). Ждать тут нечего: чем раньше уйдём на запасной
//    канал, тем короче «Подключаюсь…» у пользователя;
//  - хендшейк ЕСТЬ, но egress не подтвердился → UDP ходит, а трафика нет. Обычно это не блокировка, а
//    пир, который на сервере ещё не появился (sync-таймер) или медленная сота. Рвать рабочий путь
//    рано нельзя — даём больше времени.
//
// Оба порога заметно короче полного набора egress-проб (~34с): сторож для того и нужен, чтобы не
// заставлять пользователя ждать полминуты там, где ответ уже известен.
package org.amnezia.awg.mayak.core

object FallbackDecision {

    /** Нет ни одного хендшейка за это время — UDP не доходит, уходим на запасной канал. */
    const val NO_HANDSHAKE_MS = 6_000L

    /** Хендшейк есть, но egress так и не подтвердился за это время — тоже уходим. */
    const val NO_EGRESS_MS = 10_000L

    /**
     * @param elapsedMs    сколько прошло с подъёма туннеля.
     * @param hasHandshake был ли хоть один успешный хендшейк с сервером.
     * @return true — пора переключаться на запасной канал (вызывать, пока egress НЕ подтверждён;
     *         подтвердился — вопрос снят, никакого переключения не нужно).
     */
    fun shouldSwitch(elapsedMs: Long, hasHandshake: Boolean): Boolean =
        elapsedMs >= if (hasHandshake) NO_EGRESS_MS else NO_HANDSHAKE_MS
}
