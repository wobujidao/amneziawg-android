// FallbackDecision — когда пора уходить с UDP на следующую ступень лестницы (SPEC-0039 T5).
//
// Решение вынесено сюда, в :core, по двум причинам: пороги должны быть В ОДНОМ месте (а не размазаны
// по Activity), и их надо проверять тестом на JVM, а не «на телефоне владельца».
//
// Почему два разных порога, а не один:
//  - хендшейка НЕТ вовсе → наши UDP-пакеты не доходят до сервера в принципе (оператор душит весь UDP —
//    ровно случай, ради которого сделан SPEC-0039). Ждать тут нечего: чем раньше уйдём на следующую
//    ступень, тем короче «Подключаюсь…» у пользователя;
//  - хендшейк ЕСТЬ, но egress не подтвердился → UDP ходит, а трафика нет. Обычно это не блокировка, а
//    пир, который на сервере ещё не появился (sync-таймер) или медленная сота. Рвать рабочий путь
//    рано нельзя — даём больше времени.
//
// ⚠️ ОТКУДА СЧИТАЕТСЯ ВТОРОЙ ПОРОГ — на этом обожглись на живом пользователе 2026-07-28.
//
// Раньше оба порога считались от ПОДЪЁМА ТУННЕЛЯ. Выглядело разумно, но означало вот что: медленное
// рукопожатие съедало время, отведённое на проверку трафика. В диаг-логе владельца (#63) первый пакет
// рукопожатия потерялся — обычное дело на соте, — повтор ушёл через 5 с, рукопожатие состоялось на
// 6,5 с. На подтверждение egress осталось 3,5 с вместо обещанных десяти, проба не уложилась, и
// приложение увело человека с РАБОЧЕГО прямого пути на транзит через Москву. Обещание «рвать рабочий
// путь рано нельзя» не выполнялось ровно тогда, когда было нужнее всего: чем хуже связь, тем меньше
// времени оставалось на проверку.
//
// Теперь второй порог отсчитывается ОТ МОМЕНТА, КОГДА УВИДЕЛИ РУКОПОЖАТИЕ. Медленное рукопожатие
// больше не отнимает бюджет у пробы. Худший случай ограничен сам собой: если рукопожатия нет к
// NO_HANDSHAKE_MS, уходим по первому порогу, поэтому суммарное ожидание не превышает
// NO_HANDSHAKE_MS + NO_EGRESS_MS ≈ 16 с — всё ещё вдвое короче полного набора проб (~34 с).
package org.amnezia.awg.mayak.core

object FallbackDecision {

    /** Нет ни одного хендшейка за это время (с подъёма туннеля) — UDP не доходит, уходим дальше. */
    const val NO_HANDSHAKE_MS = 6_000L

    /** Хендшейк есть, но egress не подтвердился за это время ПОСЛЕ хендшейка — тоже уходим. */
    const val NO_EGRESS_MS = 10_000L

    /**
     * @param elapsedMs     сколько прошло с подъёма туннеля.
     * @param handshakeAtMs на какой миллисекунде (от подъёма) ВПЕРВЫЕ увидели хендшейк; null — ещё нет.
     * @return true — пора переключаться на следующую ступень (вызывать, пока egress НЕ подтверждён;
     *         подтвердился — вопрос снят, никакого переключения не нужно).
     */
    fun shouldSwitch(elapsedMs: Long, handshakeAtMs: Long?): Boolean =
        if (handshakeAtMs == null) elapsedMs >= NO_HANDSHAKE_MS
        else elapsedMs - handshakeAtMs >= NO_EGRESS_MS

    /**
     * Сколько ещё МОЖНО ждать до переключения (мс, не меньше 1).
     *
     * Нужен, чтобы порог был настоящим: проба egress ходит в сеть через туннель, который как раз не
     * работает, и её собственный таймаут порогов не знает — при мёртвом DNS один вызов занимал ~37 с
     * (живой разбор 2026-07-27). Вызывающий ограничивает пробу этим остатком, и решение принимается
     * ровно тогда, когда обещано.
     */
    fun msLeft(elapsedMs: Long, handshakeAtMs: Long?): Long =
        (if (handshakeAtMs == null) NO_HANDSHAKE_MS - elapsedMs
        else NO_EGRESS_MS - (elapsedMs - handshakeAtMs)).coerceAtLeast(1L)
}
