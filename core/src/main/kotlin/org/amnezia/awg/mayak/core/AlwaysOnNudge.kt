// Решение «показывать ли разговор про постоянное подключение» (Always-On). Чистое правило —
// вынесено из Activity/MayakPrefs (там SharedPreferences и Android), чтобы его можно было проверить
// юнит-тестом на обычном JVM, без эмулятора. См. MayakActivity.maybeShowAlwaysOnNudge.
//
// Зачем разговор вообще нужен: в глубоком Doze (экран погашен, телефон в кармане/лифте) система
// выгружает наш процесс, туннель умирает и сам НЕ встаёт — человек остаётся без интернета до тех
// пор, пока не откроет приложение. Единственное рабочее лечение сегодня — системная настройка
// «постоянное подключение», включить которую за человека мы не можем. Авто-переподъём при смене
// сети трогать нельзя: выкатывали дважды и дважды делали хуже (откат 0.3.78).
package org.amnezia.awg.mayak.core

object AlwaysOnNudge {
    /** Ещё не заговаривали — единственное состояние, в котором разговор уместен. */
    const val NOT_ASKED = 0

    /** «Позже». Запоминается навсегда: повторно долбить человека тем же окном мы не будем. */
    const val POSTPONED = 1

    /**
     * «Уже включено» — человек сам сказал, что настройка у него стоит. Отдельно от POSTPONED
     * намеренно: это не отсрочка, а утверждение о состоянии телефона. Проверить его мы не можем
     * (см. MayakAlwaysOn), но и спорить с человеком не будем.
     */
    const val CONFIRMED = 2

    /** Ушёл по кнопке в системный раздел. Включил он там или передумал — нам не видно. */
    const val SENT_TO_SETTINGS = 3

    /**
     * Показывать ли карточку.
     *
     * @param decision что человек уже ответил (NOT_ASKED / POSTPONED / CONFIRMED / SENT_TO_SETTINGS).
     * @param connectCount сколько успешных подключений было за всё время установки. Разговор
     *   заводим ПОСЛЕ первого: до него объяснять «связь рвётся во сне» не о чем — человек ещё ни
     *   разу не подключался, и окно поверх пустого экрана читалось бы как реклама настроек.
     * @param alwaysOnProven система ДОКАЗАЛА, что постоянное подключение уже наше и уже включено.
     *   Только положительный ответ имеет смысл: «не смогли прочитать» и «выключено» для приложения
     *   неразличимы, поэтому неизвестность НЕ считается выключенным состоянием (см. MayakAlwaysOn).
     */
    fun shouldShow(decision: Int, connectCount: Int, alwaysOnProven: Boolean): Boolean {
        if (alwaysOnProven) return false
        if (decision != NOT_ASKED) return false
        return connectCount >= 1
    }
}
