package org.amnezia.awg.mayak.core

/**
 * Публичный НОМЕР АККАУНТА на стороне клиента: показ и ничего больше.
 *
 * Что это. С 08-08 у каждой учётки есть номер вида «472-918-563» — девять цифр, последняя
 * контрольная (алгоритм Дамма). Это главный якорь разговора с поддержкой: человека надо как-то
 * называть, а почта в схеме необязательна (учётки из бота и подарочные заводятся без неё).
 * Серверная сторона — пакет `internal/acctnum` в ядре, миграция 0110.
 *
 * 🔴 ХРАНЕНИЕ И ПОКАЗ — РАЗНЫЕ ВЕЩИ. Ядро отдаёт и хранит РОВНО ДЕВЯТЬ ЦИФР без разделителей,
 * дефисы добавляет показ. Ведущие нули ЗНАЧИМЫ: «007891234» — законный номер, а не «7891234»,
 * поэтому номер живёт строкой и НИКОГДА не превращается в число (Int/Long съел бы нули молча).
 *
 * ⚠️ Номер — ИМЯ, а НЕ ПАРОЛЬ. Он не даёт доступа и не участвует в аутентификации: прятать его от
 * человека не надо (для этого он и заведён), но и рассылать наружу незачем — в телеметрию он не
 * попадает, только в письмо поддержке и в диагностический лог, то есть туда, куда человек его
 * отправляет сам и осознанно.
 *
 * Почему проверки контрольной цифры здесь НЕТ. Проверять номер, который выдало НАШЕ ЖЕ ядро, —
 * значит дать клиенту право спрятать законный номер, если арифметика двух реализаций разойдётся
 * (08-08 такое уже случалось между Go и SQL). Разбор введённого руками номера — задача сервера
 * (`acctnum.Normalize`), у показа задача одна: не соврать и не упасть.
 */
object AccountNumber {

    /** Длина нормализованного номера — ровно столько цифр отдаёт ядро (acctnum.Length). */
    const val LENGTH = 9

    /**
     * Ключ в SecureStore. Номер лежит там же, где email аккаунта — не потому, что он секрет (он им
     * не является), а потому что у него ТОТ ЖЕ жизненный цикл: он про конкретную учётку и обязан
     * исчезнуть при выходе, иначе следующий вошедший продиктует поддержке чужой номер.
     */
    const val STORE_KEY = "account_number"

    /** Сохранённый номер (как пришёл от ядра) или null, если его там нет или лежит невнятное. */
    fun cached(store: SecureStore): String? = store.get(STORE_KEY)?.takeIf { isShowable(it) }

    /** Готовая к показу и к диктовке строка «472-918-563» или null, если показывать нечего. */
    fun display(store: SecureStore): String? = cached(store)?.let { format(it) }

    /**
     * Запомнить то, что пришло от ядра, и вернуть готовую к показу строку.
     *
     * 🔴 Пустое/невнятное `fromCore` НЕ СТИРАЕТ сохранённый номер. Это главное правило этой функции:
     * отсутствие поля в ответе означает «ядро старее правки» или «сети не было», а не «номера у
     * человека больше нет». Стирали бы — номер пропадал бы из письма в поддержку при первом же
     * отказе, ровно тогда, когда письмо и пишут.
     */
    fun remember(store: SecureStore, fromCore: String?): String? {
        if (isShowable(fromCore)) store.put(STORE_KEY, fromCore!!.trim())
        return display(store)
    }

    /** Забыть номер: вызывается при выходе из аккаунта вместе с токеном и email. */
    fun forget(store: SecureStore) = store.remove(STORE_KEY)

    /**
     * Есть ли что показывать. true — строка состоит из цифр (допускаются дефисы и пробелы, если
     * номер уже пришёл размеченным) и хотя бы одна цифра в ней есть.
     *
     * Список допустимых символов ЗАКРЫТЫЙ, а не «всё, кроме букв»: увидев в поле номера что-то
     * непохожее на номер, экран лучше промолчит, чем покажет мусор с подписью «ваш номер».
     */
    fun isShowable(raw: String?): Boolean {
        val s = raw?.trim() ?: return false
        var digits = 0
        for (c in s) {
            when {
                c in '0'..'9' -> digits++
                c == '-' || c == ' ' -> Unit
                else -> return false
            }
        }
        return digits > 0
    }

    /**
     * Как номер показывают человеку и как он читает его вслух: «472-918-563».
     *
     * Ровно девять цифр → три блока по три. Всё остальное отдаём КАК ПРИШЛО (обрезав пробелы):
     * у показа нет права ронять экран из-за неожиданной строки — и нет права врать, будто мусор
     * отформатирован. Тот же контракт, что у `acctnum.Format` в ядре.
     *
     * Номер длиннее девяти цифр — не ошибка на будущее: ёмкость 10^8 конечна, и когда номер
     * удлинят миграцией, старое приложение покажет его без разметки, а не спрячет.
     *
     * null («поля в ответе ядра нет») → пустая строка: показывать нечего, и это штатный случай.
     */
    fun format(raw: String?): String {
        val s = raw?.trim() ?: return ""
        // Сначала тот же фильтр, что у isShowable: иначе «CARD 472918563» разметилось бы как номер
        // (девять цифр в строке есть), и показ соврал бы про то, чего в поле не лежит.
        if (!isShowable(s)) return s
        val digits = StringBuilder(LENGTH)
        for (c in s) if (c in '0'..'9') digits.append(c)
        if (digits.length != LENGTH) return s
        val d = digits.toString()
        return d.substring(0, 3) + "-" + d.substring(3, 6) + "-" + d.substring(6, 9)
    }
}
