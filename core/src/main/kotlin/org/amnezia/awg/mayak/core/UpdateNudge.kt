// Ступенчатые напоминания об обновлении: чем дольше человек сидит на старой сборке, тем настойчивее
// напоминание. Чистое правило, без Android — проверяется юнит-тестом на JVM.
//
// Что было не так. Между «мягко предложили один раз» и «жёстко отрезали по min_version_code» у нас
// не было ничего: человек нажимал «Позже», и приложение замолкало про эту версию НАВСЕГДА
// (updateDismissedCode >= latest). Сборка с починенным протоколом до него не доезжала, а рубильник
// порога — слишком грубый инструмент, чтобы дёргать его ради обычного релиза.
//
// Как теперь. У каждой НОВОЙ версии свой отсчёт: день 0 — обычное предложение, дни 14 и 21 —
// повторные (текст жёстче), с 36-го дня напоминаем на каждом холодном старте. Отсчёт идёт от того
// момента, когда приложение ВПЕРВЫЕ увидело эту версию, а не от даты релиза: человек, поставивший
// приложение позже, не должен сразу получить «ваша сборка очень старая».
package org.amnezia.awg.mayak.core

object UpdateNudge {

    /** Пороги в днях. Индекс = номер ступени; последняя ступень повторяется каждый холодный старт. */
    val STEP_DAYS = intArrayOf(0, 14, 21, 36)

    /** Ступени ещё не показывали ни одной. */
    const val NO_STEP = -1

    /** Нечего показывать. */
    const val NONE = -1

    /**
     * Какую ступень показать сейчас.
     *
     * @param daysSinceFirstSeen сколько дней прошло с момента, когда приложение впервые узнало об
     *   этой версии.
     * @param lastShownStep последняя показанная ступень для ЭТОЙ версии (NO_STEP — ни одной).
     * @return номер ступени (0..3) или NONE. Последняя ступень возвращается снова и снова: сборка
     *   старше 36 дней — это уже риск для человека, тут молчать вредно.
     */
    fun stepToShow(daysSinceFirstSeen: Long, lastShownStep: Int): Int {
        var due = NONE
        for (i in STEP_DAYS.indices) {
            if (daysSinceFirstSeen >= STEP_DAYS[i]) due = i
        }
        if (due == NONE) return NONE
        val last = STEP_DAYS.size - 1
        // Последняя ступень: показываем всегда, даже если уже показывали.
        if (due == last) return last
        return if (due > lastShownStep) due else NONE
    }

    /**
     * Пора ли сбросить отсчёт: версия на сервере сменилась (вышла ещё более свежая) — значит у неё
     * своя история напоминаний, а не унаследованная от предыдущей.
     */
    fun isNewVersion(latestCode: Int, trackedCode: Int): Boolean = latestCode != trackedCode

    /** Дней между двумя моментами (мс). Отрицательная разница (часы переставили назад) — это 0. */
    fun daysBetween(firstSeenMs: Long, nowMs: Long): Long {
        val d = (nowMs - firstSeenMs) / 86_400_000L
        return if (d < 0) 0 else d
    }
}
