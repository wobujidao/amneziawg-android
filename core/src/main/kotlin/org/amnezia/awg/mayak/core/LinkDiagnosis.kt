// LinkDiagnosis — вердикт диагностики связи СЛОВАМИ, из набора отдельных проверок.
//
// ⚠️ ЗАЧЕМ ЭТО ВООБЩЕ ПОЯВИЛОСЬ. Замечание владельца 21-08, дословно: «у меня подключение работает,
// но связи нет. И если я нажимаю проверить, получается что проверка уже обрывает линию и начинает
// подключаться вновь. А нужно было проверять именно на этой линии, не переподключая её».
//
// Кнопка «Проверить связь» до этого прогоняла ВСЮ лестницу заново — то есть первым делом рвала
// живой туннель, уничтожая ровно то состояние, которое человек и хотел показать. Случай
// «подключено, но трафик не идёт» она убивала раньше, чем успевала измерить, и рапортовала, что
// ступени в порядке.
//
// Здесь — ЧИСТАЯ логика (без Android): из ответов проверок собирается один вывод человеческим
// языком. Сами проверки делает :ui (у него сеть, туннель и системные признаки), а решение «что это
// значит» живёт здесь и проверяется тестами на JVM — по той же причине, что FallbackDecision и
// LivenessDecision.
//
// 🔴 ГЛАВНОЕ ПРАВИЛО ВЕРДИКТА: не гадать. Каждая проверка может ответить «да», «нет» или «не
// проверяли», и третье — полноправный ответ, а не повод додумать. Вывод собирается только из того,
// что реально измерено: неизвестное не превращается ни в успех, ни в провал (та же ошибка, из-за
// которой лог из одних «ПРОВАЛ» описывал успешное подключение — память
// log-iz-odnih-provalov-mozhet-byt-uspehom).
package org.amnezia.awg.mayak.core

/** Ответ одной проверки. `UNKNOWN` — «не проверяли или не смогли»; это НЕ «нет». */
enum class Probe { OK, FAIL, UNKNOWN }

/**
 * Что удалось измерить на ТЕКУЩЕЙ линии, ничего не переподключая.
 *
 * Порядок полей — порядок вопросов, которые задаёт человек: сначала «а интернет-то есть», потом «а
 * до вас доходит», потом «а через туннель идёт».
 */
data class LinkFacts(
    /** 1. Интернет ВООБЩЕ — запрос МИМО туннеля. Нет → дело не в нас. */
    val internetOutside: Probe = Probe.UNKNOWN,
    /** 2. Отвечает ли ВЫХОД (нода) — мимо туннеля. Нет → нода недоступна или её режут. */
    val exitReachable: Probe = Probe.UNKNOWN,
    /** 3. Идёт ли трафик ЧЕРЕЗ туннель наружу. */
    val throughTunnel: Probe = Probe.UNKNOWN,
    /** 4. Разрешаются ли имена сайтов через туннель. */
    val dnsThroughTunnel: Probe = Probe.UNKNOWN,
    /** 5. Проходит ли через туннель КРУПНЫЙ пакет (мелкие проходят почти всегда). */
    val bigPacket: Probe = Probe.UNKNOWN,
    /** 6. Жив ли сам туннель на уровне протокола: свежее рукопожатие И рост принятых байт. */
    val tunnelAlive: Probe = Probe.UNKNOWN,
    /** 7. Сходятся ли часы телефона с сервером (расхождение ломает TLS и рукопожатия). */
    val clockOk: Probe = Probe.UNKNOWN,
    /** 8. Держит ли сеть кто-то ещё: чужой VPN поверх нашего. */
    val otherVpn: Probe = Probe.UNKNOWN,
    /** 9. Проходит ли UDP вообще (нет → прямая ступень бессмысленна, надо на мост). */
    val udpPasses: Probe = Probe.UNKNOWN,
    /** 10. Доступны ли МЫ САМИ мимо туннеля — по имени и по запасному адресу отдельно. */
    val apiByName: Probe = Probe.UNKNOWN,
    val apiByIp: Probe = Probe.UNKNOWN,
    /**
     * 11. Отвечает ли адрес из «белого списка» (Яндекс, VK) МИМО туннеля.
     *
     * Зачем отдельная проба. При веерном ограничении мобильного интернета сеть пускает только
     * несколько российских сервисов, а всё остальное молчит — в том числе api.ipify.org, по
     * которому мы судим «есть ли интернет вообще». Без этой пробы вердикт получался
     * «на телефоне нет интернета, проверьте сеть или Wi-Fi», хотя интернет у человека ЕСТЬ.
     * Спрашиваем только тогда, когда всё остальное молчит: в норме лишний запрос не нужен.
     */
    val ruAllowedHost: Probe = Probe.UNKNOWN,
    /** Включены ли ограничения фона/энергосбережения для приложения (не проба, а факт системы). */
    val batteryRestricted: Boolean = false,
)

/** Вердикт: одна фраза человеку + короткий машинный код для журнала и разбора. */
data class LinkVerdict(val code: String, val text: String)

object LinkDiagnosis {

    // Коды вердиктов. Ими же помечается отчёт в панели, поэтому они стабильны и не переводятся.
    const val NO_NETWORK = "no_network"
    const val MOBILE_ALLOWLIST = "mobile_allowlist"
    const val OTHER_VPN = "other_vpn"
    const val CLOCK_SKEW = "clock_skew"
    const val EXIT_UNREACHABLE = "exit_unreachable"
    const val TUNNEL_DEAD = "tunnel_dead"
    const val DNS_BROKEN = "dns_broken"
    const val MTU_BROKEN = "mtu_broken"
    const val WORKS = "works"
    const val UNCLEAR = "unclear"

    /**
     * Вывод из фактов. Порядок ветвей — от причины к следствию: сперва то, что делает все остальные
     * измерения бессмысленными (нет сети, чужой VPN, разъехавшиеся часы), потом путь по звеньям.
     *
     * Почему порядок важен: при отсутствии сети провалятся ВСЕ пробы, и вердикт «через туннель не
     * идёт» был бы формально верным и совершенно бесполезным — человек пошёл бы чинить не то.
     */
    fun verdict(f: LinkFacts): LinkVerdict {
        // 🔴 РАНЬШЕ «нет интернета»: веерное ограничение мобильной сети. Наши молчат, зарубежный
        // адрес молчит, а российский из белого списка ОТВЕЧАЕТ — значит интернет есть, просто сеть
        // сейчас пускает только часть сайтов. Без этой ветки человек читал «на телефоне нет
        // интернета, проверьте сеть», то есть его отправляли чинить исправную сеть.
        if (f.internetOutside == Probe.FAIL && f.ruAllowedHost == Probe.OK) {
            return LinkVerdict(MOBILE_ALLOWLIST,
                "Мобильный интернет сейчас пускает только часть сайтов — это ограничение сети, а не поломка приложения. " +
                    "Через Wi-Fi подключение работает. Когда ограничение снимут, всё заработает само.")
        }
        // Нет интернета вовсе — остальное не имеет смысла измерять и тем более объяснять.
        if (f.internetOutside == Probe.FAIL) {
            return LinkVerdict(NO_NETWORK, "На телефоне нет интернета — ни через нас, ни без нас. Проверьте сеть или Wi-Fi.")
        }
        // Чужой VPN поверх нашего: наш трафик уходит в чужой туннель, и любые цифры ниже — про него.
        if (f.otherVpn == Probe.FAIL) {
            return LinkVerdict(OTHER_VPN, "Похоже, работает ещё одно VPN-приложение. Выключите его — два туннеля поверх друг друга не уживаются.")
        }
        // Часы: расхождение ломает защищённое соединение раньше, чем что-либо ещё.
        if (f.clockOk == Probe.FAIL) {
            return LinkVerdict(CLOCK_SKEW, "Часы на телефоне сильно расходятся с настоящим временем. Включите автоматическое время — иначе защищённое соединение не устанавливается.")
        }
        // До выхода не достучались МИМО туннеля — значит дело не в туннеле, а в пути до ноды.
        if (f.exitReachable == Probe.FAIL && f.internetOutside == Probe.OK) {
            return LinkVerdict(EXIT_UNREACHABLE, "Интернет есть, но до нашего сервера не достучаться — похоже, его режет ваш оператор. Помогает переключение страны или запасной канал.")
        }
        // Туннель не везёт трафик, хотя сеть есть и нода отвечает — это и есть тот случай, ради
        // которого всё затевалось: раньше он был неотличим от «просто не работает».
        if (f.throughTunnel == Probe.FAIL && f.internetOutside == Probe.OK) {
            // Уточняем причину, если сумели измерить.
            if (f.bigPacket == Probe.FAIL) {
                return LinkVerdict(MTU_BROKEN, "Соединение есть, но крупные пакеты через него не проходят — поэтому страницы висят, хотя туннель «подключён». Это лечится на нашей стороне, отчёт уже у нас.")
            }
            if (f.tunnelAlive == Probe.FAIL) {
                return LinkVerdict(TUNNEL_DEAD, "Туннель числится поднятым, но данные через него не идут. Переподключитесь — а если повторится, отчёт уже у нас.")
            }
            return LinkVerdict(TUNNEL_DEAD, "Сеть есть и сервер отвечает, а через туннель трафик не идёт. Отчёт уже у нас.")
        }
        // Трафик идёт, но имена не разрешаются — «интернет есть, сайты не открываются».
        if (f.throughTunnel == Probe.OK && f.dnsThroughTunnel == Probe.FAIL) {
            return LinkVerdict(DNS_BROKEN, "Соединение работает, но имена сайтов не разрешаются. Попробуйте сменить профиль DNS в настройках.")
        }
        // Всё измеренное в порядке — но говорим это ТОЛЬКО если главное действительно измерено.
        if (f.throughTunnel == Probe.OK && f.internetOutside == Probe.OK) {
            return LinkVerdict(WORKS, "Связь в порядке: интернет есть, сервер отвечает, трафик через туннель идёт.")
        }
        // 🔴 Не хватает измерений — так и говорим. Соблазн написать «всё хорошо» здесь и есть тот
        // самый способ соврать: молчание проверок не означает их успех.
        return LinkVerdict(UNCLEAR, "Не удалось проверить всё до конца. Повторите через минуту — если повторится, отправьте отчёт.")
    }

    /**
     * Короткая машинная строка для журнала и панели: только то, что реально измерено.
     * Непроверенное НЕ упоминается вовсе — иначе отчёт выглядел бы полнее, чем он есть.
     */
    fun trace(f: LinkFacts): String = buildList {
        fun добавить(имя: String, p: Probe) {
            when (p) {
                Probe.OK -> add("$имя ✓")
                Probe.FAIL -> add("$имя ✗")
                Probe.UNKNOWN -> Unit
            }
        }
        добавить("интернет", f.internetOutside)
        добавить("выход", f.exitReachable)
        добавить("через туннель", f.throughTunnel)
        добавить("DNS", f.dnsThroughTunnel)
        добавить("крупный пакет", f.bigPacket)
        добавить("живость", f.tunnelAlive)
        добавить("часы", f.clockOk)
        добавить("чужой VPN", f.otherVpn)
        добавить("UDP", f.udpPasses)
        добавить("наш адрес по имени", f.apiByName)
        добавить("наш адрес по IP", f.apiByIp)
        добавить("белый список", f.ruAllowedHost)
        if (f.batteryRestricted) add("фон ограничен ✗")
    }.joinToString(" · ")
}
