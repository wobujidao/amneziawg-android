// Порог старых сборок — КЛИЕНТСКАЯ половина. Правило «работает ли ещё эта сборка».
//
// Серверная половина живёт с 08-08: панель `/app-versions` пишет `min_version_code` в `app_settings` и
// ПРОПИСЫВАЕТ его в тот же `version.json`, который приложение уже читает для самообновления (файл
// отдают оба пути — Caddy на домене и client-api на IP-фолбэке). Клиент про поле не знал ВООБЩЕ:
// выпустив сборку со сломанным протоколом, снять её с людей было нечем, а человек на отрезанной
// сборке получал не объяснение, а непонятные отказы ядра — то есть выглядело это как «приложение
// сломалось», и шёл он не обновляться, а в поддержку.
//
// Правило вынесено в :core чистой функцией по образцу AccessDenial/AlwaysOnNudge: внутри Activity его
// можно проверить только эмулятором, а неверное решение здесь стоит дороже любого другого в
// приложении — оно ЗАПИРАЕТ человека, которому мы ничем больше помочь не можем.
//
// 🔴 Три предохранителя, все на одну сторону — «наша ошибка не должна запирать людей»:
//   1. порог 0 (или мусор, или поля нет) — гейта нет;
//   2. версия РОВНО равна порогу — пускаем (порог задаёт минимально ДОПУСТИМУЮ сборку, не «строго выше»);
//   3. порог ВЫШЕ самой свежей выложенной сборки — гейта нет: обновляться некуда, и неотменяемый
//      экран с кнопкой «Обновить», ставящей ту же самую версию, — это тупик для ВСЕХ, включая
//      только что установивших. Опечатка в панели («79» вместо «78») не должна закрывать продукт.
package org.amnezia.awg.mayak.core

import kotlinx.serialization.json.JsonElement
import kotlinx.serialization.json.JsonPrimitive

/**
 * Что делать со сборкой, которую отрезал порог.
 *
 * Канал установки меняет не «блокировать или нет», а КУДА вести человека, и различать его
 * обязательно: сборка с сайта подписана нашим ключом, сборка из Play — ключом Google (Play App
 * Signing). Предложить человеку из Play скачать APK с сайта означает отправить его ждать загрузку,
 * которая гарантированно упадёт на несовпадении подписи, — и это на экране, с которого ему больше
 * некуда деться. Самообновление в Play-сборке к тому же запрещено политикой магазина.
 */
enum class OutdatedBuild {
    /** Сборка живая — работаем как раньше. */
    NONE,

    /** Отрезана; сборка с сайта, ссылка на APK есть — качаем сами (самообновление у нас есть). */
    UPDATE_FROM_SITE,

    /**
     * Отрезана; сборка с сайта, но пригодной ссылки на APK в version.json нет. Ведём на сайт руками:
     * гейт без работающей кнопки — худшее, что можно сделать, человек остаётся в тупике.
     */
    OPEN_SITE,

    /** Отрезана; сборка из Play — обновляет сам Play. */
    OPEN_IN_PLAY,
}

/**
 * Работает ли ещё эта сборка, и если нет — куда вести человека.
 *
 * @param versionCode `BuildConfig.VERSION_CODE` этой сборки.
 * @param minVersionCode порог из version.json (`min_version_code`); 0 — гейта нет. Мусор к нулю
 *   приводит [minVersionCodeOf] ещё при разборе файла.
 * @param latestVersionCode самая свежая выложенная сборка (`latest_version_code`). Нужен как
 *   предохранитель: порог выше неё бессмыслен — обновиться до него не может никто.
 * @param fromPlay приложение установлено из Google Play (`MayakUpdater.installedFromPlay`).
 * @param apkUrl ссылка на APK из того же version.json.
 */
fun outdatedBuild(
    versionCode: Int,
    minVersionCode: Int,
    latestVersionCode: Int,
    fromPlay: Boolean,
    apkUrl: String,
): OutdatedBuild {
    if (minVersionCode <= 0) return OutdatedBuild.NONE // порога нет (или мусор/отрицательное значение)
    if (versionCode >= minVersionCode) return OutdatedBuild.NONE // равна порогу — ПУСКАЕМ
    if (latestVersionCode < minVersionCode) return OutdatedBuild.NONE // обновляться некуда — не запираем
    if (fromPlay) return OutdatedBuild.OPEN_IN_PLAY
    // Ссылку проверяем на пригодность здесь же: пусто/http/мусор → отправим на сайт, а не покажем
    // кнопку, которая молча ничего не делает (MayakUpdater.download такую ссылку всё равно отвергнет).
    return if (apkUrl.startsWith("https://")) OutdatedBuild.UPDATE_FROM_SITE else OutdatedBuild.OPEN_SITE
}

/**
 * Порог из сырого значения `min_version_code`: число, строка с числом — годятся; всё остальное → 0.
 *
 * Зачем сырьём, а не полем `Int`. При строгом разборе (`isLenient=false`) строка или мусор в этом
 * поле ронял разбор ВСЕГО version.json: приложение теряло не только порог, но и самообновление —
 * то есть наша опечатка на сервере отрезала людей от единственного способа починиться.
 *
 * Тот же набор допустимых значений, что и у серверной половины (`jsonInt` в
 * `internal/admin/appversions.go`): «77» строкой годится, «1.5» и «abc» — нет. Формула записана в
 * двух языках, и разъехаться она обязана только вместе — расхождение здесь означало бы, что панель
 * показывает владельцу один порог, а приложение живёт по другому.
 */
fun minVersionCodeOf(raw: JsonElement?): Int {
    val primitive = raw as? JsonPrimitive ?: return 0 // нет поля, null, объект, массив — гейта нет
    return primitive.content.trim().toIntOrNull() ?: 0
}
